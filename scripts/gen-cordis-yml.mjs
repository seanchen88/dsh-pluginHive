#!/usr/bin/env node
/**
 * Generate the `cordis.yml` overlay for local development.
 *
 * Each panel is mounted as ONE Loader entry keyed by its bare npm package name.
 * The bare name is required, not just convenient: the Web client-module system
 * attaches a package's built `./client` half to the row whose specifier is the
 * bare package name, and `typert-loader` resolves that package's `package.json`
 * to import its generated `./typert` host face. A row pointed at a `src/*.ts`
 * path loads the host half but never carries the client half or the Remote.
 *
 * So this repo's packages must be resolvable (linked into the harness workspace
 * or `pnpm link`ed) and BUILT (`pnpm build`) before the overlay is applied:
 *
 *   cd ../deepseek-harness && pnpm dsh web --patch <this-repo>/cordis.yml
 *
 * Adding a new panel: append its package name to PANELS below.
 */
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { writeFile } from 'node:fs/promises'

const repoRoot = dirname(dirname(fileURLToPath(import.meta.url)))

/** One insert row per panel; `name` is the bare package name (see header). */
const PANELS = [
  { id: 'mcp-panel', pkg: '@dsh-plugins/mcp-panel' },
  { id: 'skill-panel', pkg: '@dsh-plugins/skill-panel' },
  // Sidebar entry below 「插件」; installs delegate to the mcp-panel write path,
  // so keep it after mcp-panel in the list to preserve load order.
  { id: 'market-panel', pkg: '@dsh-plugins/mcp-market-panel' },
  // The copy-me template; comment out to omit the demo section.
  { id: 'example-panel', pkg: '@dsh-plugins/example-panel' },
]

const rows = PANELS.map(panel =>
  `  - id: ${panel.id}\n    name: '${panel.pkg}'`,
).join('\n')

const document = `# Generated by scripts/gen-cordis-yml.mjs — do not edit by hand.\n`
  + `# Requires the packages below to be linked into the harness workspace and built.\n`
  + `- insert:\n${rows}\n`

const target = join(repoRoot, 'cordis.yml')
await writeFile(target, document, 'utf8')
console.log(`[gen-cordis-yml] wrote ${target}`)
for (const panel of PANELS) console.log(`  - ${panel.id} -> ${panel.pkg}`)
